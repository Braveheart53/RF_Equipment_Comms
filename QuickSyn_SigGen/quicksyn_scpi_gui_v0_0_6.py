#: Initial height of the docked SCPI console, in pixels (about ten lines).
CONSOLE_DOCK_HEIGHT_PX: int = 220
#: Preferred initial window size; clamped to the screen's available area.
WINDOW_SIZE_PX: tuple[int, int] = (1180, 960)


class ScpiConsole(QtWidgets.QWidget):
    """Live view of every SCPI exchange: commands sent, replies received.

    Exchanges arrive through ``AppController.transactionLogged``, a Qt signal,
    so those made on the sampler thread are delivered to the GUI thread by a
    queued connection. ``add_transaction`` only files the exchange (constant
    time); a timer renders whatever is new every ``FLUSH_MS``, so a fast
    telemetry stream (100+ exchanges per second) never stalls the window.

    Sources: ``GUI`` = sent by a user action (connect, Main control, lists,
    sweeps ...); ``POLL`` = sent by the telemetry sampler. Polls are hidden by
    default so user commands stand out; tick *Show telemetry polls* to see
    them.

    Bounds (memory and GUI time), whatever the session length and however
    long the view stays paused:

    * Each source has its own store of at most ``MAX_RECORDS`` exchanges, so
      a fast poll stream can never push your own commands out of the history
      that the filter searches.
    * Nothing else is queued. Pausing only stops drawing; on *Resume* the
      newest exchanges are drawn straight from the stores (0.0.5 queued every
      exchange while paused: 45 MB and a 62 s freeze after 200 000).
    * One render draws at most ``MAX_LINES`` lines, the most the view can
      hold. Anything older is summarised in one grey ``...`` notice line.
    * Lines are inserted with a text cursor and character formats, about
      ten times faster than parsing HTML, and spacing is exact, so replies
      line up under their commands.
    """

    MAX_LINES = 5000            #: text-view line limit (oldest dropped)
    MAX_RECORDS = 20_000        #: exchanges retained PER SOURCE for re-filtering
    FLUSH_MS = 150              #: render interval
    FILTER_DELAY_MS = 250       #: typing pause before a filter is applied
    #: Mid-tone colours that stay legible on light and dark palettes.
    COLOURS = {"cmd": "#3b7dd8", "reply": "#2e9e5b", "error": "#d9483b",
               "meta": "#8c8c8c", "poll": "#b07d2a"}

    def __init__(self, parent: QtWidgets.QWidget | None = None) -> None:
        super().__init__(parent)
        #: source -> bounded store of (sequence number, transaction, source).
        self._store: dict[str, deque[tuple[int, Transaction, str]]] = {
            "GUI": deque(maxlen=self.MAX_RECORDS),
            "POLL": deque(maxlen=self.MAX_RECORDS),
        }
        self._seq = 0                       # number of the newest exchange
        self._shown_seq = 0                 # newest exchange already drawn or skipped
        self._added: dict[str, int] = {}    # exchanges filed per source since clear
        self._shown_added: dict[str, int] = {}  # _added as it was at the last draw
        self._n_total = 0
        self._n_errors = 0
        self._n_polls = 0
        self._formats: dict[str, QtGui.QTextCharFormat] = {}
        for key, colour in self.COLOURS.items():
            fmt = QtGui.QTextCharFormat()
            fmt.setForeground(QtGui.QColor(colour))
            self._formats[key] = fmt

        layout = QtWidgets.QVBoxLayout(self)
        layout.setContentsMargins(4, 4, 4, 4)
        bar = QtWidgets.QHBoxLayout()
        self.pause_button = QtWidgets.QPushButton("Pause")
        self.pause_button.setCheckable(True)
        self.pause_button.setToolTip("Freeze the view; exchanges are still recorded "
                                     "and the newest appear when you resume.")
        self.chk_polls = QtWidgets.QCheckBox("Show telemetry polls")
        self.chk_autoscroll = QtWidgets.QCheckBox("Auto-scroll")
        self.chk_autoscroll.setChecked(True)
        self.filter_edit = QtWidgets.QLineEdit()
        self.filter_edit.setPlaceholderText("Filter: text in command or reply")
        self.filter_edit.setClearButtonEnabled(True)
        self.clear_button = QtWidgets.QPushButton("Clear")
        self.copy_button = QtWidgets.QPushButton("Copy")
        self.save_button = QtWidgets.QPushButton("Save...")
        for w in (self.pause_button, self.chk_polls, self.chk_autoscroll):
            bar.addWidget(w)
        bar.addWidget(self.filter_edit, 1)
        for w in (self.clear_button, self.copy_button, self.save_button):
            bar.addWidget(w)
        layout.addLayout(bar)

        self.view = QtWidgets.QPlainTextEdit()
        self.view.setReadOnly(True)
        self.view.setMaximumBlockCount(self.MAX_LINES)
        self.view.setLineWrapMode(QtWidgets.QPlainTextEdit.LineWrapMode.NoWrap)
        self.view.setFont(QtGui.QFontDatabase.systemFont(QtGui.QFontDatabase.SystemFont.FixedFont))
        layout.addWidget(self.view, 1)
        self.stats_label = QtWidgets.QLabel()
        layout.addWidget(self.stats_label)
        self._update_stats()

        self._timer = QtCore.QTimer(self)
        self._timer.setInterval(self.FLUSH_MS)
        self._timer.timeout.connect(self._flush)
        self._timer.start()
        # The filter is applied once typing pauses, not on every keystroke.
        self._filter_timer = QtCore.QTimer(self)
        self._filter_timer.setSingleShot(True)
        self._filter_timer.setInterval(self.FILTER_DELAY_MS)
        self._filter_timer.timeout.connect(self._rerender)
        self.pause_button.toggled.connect(self._on_pause)
        self.chk_polls.toggled.connect(self._rerender)
        # A lambda, so the text argument never reaches an overload of start().
        self.filter_edit.textChanged.connect(lambda _text: self._filter_timer.start())
        self.filter_edit.returnPressed.connect(self._rerender)
        self.clear_button.clicked.connect(self.clear)
        self.copy_button.clicked.connect(
            lambda: QtWidgets.QApplication.clipboard().setText(self.view.toPlainText()))
        self.save_button.clicked.connect(self._save_dialog)

    # --- input ---------------------------------------------------------------
    def add_transaction(self, txn: Transaction, source: str = "GUI") -> None:
        """File one exchange (slot for AppController.transactionLogged).

        Constant time and bounded memory: the exchange goes into its source's
        store and is drawn by the next timer tick (or on Resume).
        """
        self._seq += 1
        store = self._store.get(source)
        if store is None:               # an unexpected source gets its own store
            store = self._store[source] = deque(maxlen=self.MAX_RECORDS)
        store.append((self._seq, txn, source))
        self._added[source] = self._added.get(source, 0) + 1
        self._n_total += 1
        self._n_errors += 0 if txn.ok else 1
        self._n_polls += 1 if source == "POLL" else 0

    @property
    def records(self) -> list[tuple[Transaction, str]]:
        """Every retained exchange, oldest first, as (transaction, source)."""
        merged = heapq.merge(*self._store.values(), key=itemgetter(0))
        return [(txn, source) for _, txn, source in merged]

    @property
    def held_count(self) -> int:
        """Exchanges received but not yet drawn (non-zero while paused)."""
        return self._seq - self._shown_seq

    # --- formatting ------------------------------------------------------------
    def _matcher(self) -> Callable[[Transaction, str], bool]:
        """Predicate for the current poll setting and filter text."""
        show_polls = self.chk_polls.isChecked()
        needle = self.filter_edit.text().strip().lower()

        def visible(txn: Transaction, source: str) -> bool:
            if source == "POLL" and not show_polls:
                return False
            if needle:
                return needle in f"{txn.command} {txn.response or ''} {txn.error}".lower()
            return True
        return visible

    def _visible(self, txn: Transaction, source: str) -> bool:
        """Whether one exchange passes the poll setting and the filter."""
        return self._matcher()(txn, source)

    @staticmethod
    def _one_line(text: str) -> str:
        """Keep an exchange on its own line(s): show CR/LF as a visible mark."""
        return text.replace("\r\n", "\u21b5").replace("\r", "\u21b5").replace("\n", "\u21b5")

    def format_segments(self, txn: Transaction, source: str) -> list[list[tuple[str, str]]]:
        """Lines for one exchange as (text, colour key) segments.

        One line for a write (with its error, if any); two for a query: the
        command, then the reply or error indented to sit under the arrow.
        """
        stamp = datetime.fromtimestamp(txn.t_unix).strftime("%H:%M:%S.%f")[:-3]
        tag = f"{source:<4}"
        head = [(stamp + " ", "meta"), (tag + " ", "poll" if source == "POLL" else "meta")]
        pad = " " * (len(stamp) + len(tag) + 2)
        lat = f"{txn.latency_s * 1e3:.1f} ms"
        cmd = ("\u2192 " + self._one_line(txn.command), "cmd")
        if not txn.is_query:
            row = head + [cmd, (f"  (write, {lat})", "meta")]
            if not txn.ok:
                row.append(("  \u2716 " + self._one_line(txn.error or "write failed"), "error"))
            return [row]
        if txn.ok:
            reply = self._one_line(txn.response or "")
            body = ("\u2190 " + reply, "reply") if reply else ("\u2190 (empty reply)", "meta")
        else:
            body = ("\u2716 " + self._one_line(txn.error or "no reply"), "error")
        return [head + [cmd], [(pad, "meta"), body, (f"  ({lat})", "meta")]]

    def format_lines(self, txn: Transaction, source: str) -> list[str]:
        """The same lines as HTML (spaces kept as &nbsp;), e.g. for export."""
        return ["".join(f"<span style='color:{self.COLOURS[key]}'>"
                        f"{html.escape(text).replace(' ', '&nbsp;')}</span>"
                        for text, key in row)
                for row in self.format_segments(txn, source)]

    def _notice(self, count: int, approximate: bool = False) -> list[tuple[str, str]]:
        """One grey line standing in for exchanges that are not drawn."""
        plural = "" if count == 1 else "s"
        upto = "up to " if approximate else ""
        return [(f"\u22ef {upto}{count} earlier exchange{plural} not shown here (the console "
                 f"keeps the newest {self.MAX_LINES} lines); the session's "
                 f"transactions.csv holds every exchange while logging", "meta")]

    # --- rendering -------------------------------------------------------------
    def _write(self, records: list[tuple[int, Transaction, str]], lost: int = 0,
               approximate: bool = False) -> None:
        """Draw visible records, newest last, within the view's line limit.

        ``lost`` counts exchanges from a shown source that are no longer held
        (a very long pause); they are summarised with the records skipped for
        the line limit in one notice line. ``approximate`` marks the count as
        an upper bound (a filter was active, so not every lost exchange would
        have matched).
        """
        # Newest records first until the view is full, keeping one line free
        # for the notice so the line limit never trims the notice itself.
        budget, start = self.MAX_LINES - 1, len(records)
        while start > 0:
            cost = 2 if records[start - 1][1].is_query else 1
            if cost > budget:
                break
            budget -= cost
            start -= 1
        rows: list[list[tuple[str, str]]] = []
        if lost + start:
            rows.append(self._notice(lost + start, approximate and lost > 0))
        for _, txn, source in records[start:]:
            rows.extend(self.format_segments(txn, source))
        if not rows:
            return
        bar = self.view.verticalScrollBar()
        at_end = bar.value() >= bar.maximum() - 4
        doc = self.view.document()
        cursor = QtGui.QTextCursor(doc)
        cursor.movePosition(QtGui.QTextCursor.MoveOperation.End)
        first = doc.isEmpty()
        self.view.setUpdatesEnabled(False)
        cursor.beginEditBlock()
        try:
            for row in rows:
                if not first:
                    cursor.insertBlock()
                first = False
                for text, key in row:
                    cursor.insertText(text, self._formats[key])
        finally:
            cursor.endEditBlock()
            self.view.setUpdatesEnabled(True)
        if self.chk_autoscroll.isChecked() and at_end:
            bar.setValue(bar.maximum())

    def _render_new(self) -> None:
        """Draw every exchange filed since the last draw."""
        if self._seq == self._shown_seq:
            return
        visible = self._matcher()
        show_polls = self.chk_polls.isChecked()
        chunks, lost = [], 0
        for source, store in self._store.items():
            chunk = []
            for rec in reversed(store):         # newest first, stop at the drawn ones
                if rec[0] <= self._shown_seq:
                    break
                chunk.append(rec)
            chunk.reverse()
            chunks.append(chunk)
            arrived = self._added.get(source, 0) - self._shown_added.get(source, 0)
            if source != "POLL" or show_polls:
                lost += max(0, arrived - len(chunk))   # evicted before being drawn
        self._shown_seq = self._seq
        self._shown_added = dict(self._added)
        merged = heapq.merge(*chunks, key=itemgetter(0))
        self._write([r for r in merged if visible(r[1], r[2])], lost,
                    approximate=bool(self.filter_edit.text().strip()))

    def _flush(self) -> None:
        """Timer tick: draw what arrived since the last tick (unless paused)."""
        if not self.pause_button.isChecked():
            self._render_new()
        self._update_stats()

    def _rerender(self) -> None:
        """Redraw from the stores after a filter or poll-setting change.

        While paused, only exchanges up to the moment of pausing are drawn,
        so the frozen view can be searched and Resume still adds the rest.
        """
        self._filter_timer.stop()
        paused = self.pause_button.isChecked()
        limit = self._shown_seq if paused else self._seq
        visible = self._matcher()
        merged = heapq.merge(*self._store.values(), key=itemgetter(0))
        records = [r for r in merged if r[0] <= limit and visible(r[1], r[2])]
        if not paused:
            self._shown_seq = self._seq
            self._shown_added = dict(self._added)
        self.view.clear()
        self._write(records)
        self._update_stats()

    def _on_pause(self, paused: bool) -> None:
        self.pause_button.setText("Resume" if paused else "Pause")
        if not paused:
            self._render_new()
        self._update_stats()

    def _update_stats(self) -> None:
        held = self.held_count if self.pause_button.isChecked() else 0
        self.stats_label.setText(
            f"{self._n_total} exchanges ({self._n_polls} telemetry polls"
            f"{'' if self.chk_polls.isChecked() else ', hidden'}), "
            f"{self._n_errors} errors"
            + (f"  |  paused: {held} waiting" if held else ""))

    # --- actions -------------------------------------------------------------
    def clear(self) -> None:
        """Forget everything shown and retained."""
        for store in self._store.values():
            store.clear()
        self._shown_seq = self._seq
        self._added.clear()
        self._shown_added.clear()
        self._n_total = self._n_errors = self._n_polls = 0
        self.view.clear()
        self._update_stats()

    def save_to(self, path: str | Path) -> int:
        """Write the visible text to ``path``; return the number of lines."""
        text = self.view.toPlainText()
        Path(path).write_text(text + "\n", encoding="utf-8")
        return text.count("\n") + 1 if text else 0

    def _save_dialog(self) -> None:
        path, _ = QtWidgets.QFileDialog.getSaveFileName(
            self, "Save SCPI console", "scpi_console.txt", "Text files (*.txt)")
        if path:
            self.save_to(path)


class ScrollingTabWidget(QtWidgets.QTabWidget):
    """QTabWidget whose pages scroll when the window is shorter than a page.

    Without this the tallest page (Monitor and log) sets the window's minimum
    height, which left the SCPI console only a few lines and would not fit a
    small laptop screen at all. ``addTab`` wraps each page in a frameless
    QScrollArea; ``indexOf`` and ``setCurrentWidget`` accept the page itself,
    so the rest of the program keeps using the page objects.
    """

    def addTab(self, page: QtWidgets.QWidget, label: str) -> int:  # noqa: N802 (Qt API)
        area = QtWidgets.QScrollArea()
        area.setWidgetResizable(True)
        area.setFrameShape(QtWidgets.QFrame.Shape.NoFrame)
        area.setWidget(page)
        return super().addTab(area, label)

    def page(self, index: int) -> QtWidgets.QWidget | None:
        """The page at ``index`` (not its scroll area)."""
        area = self.widget(index)
        return area.widget() if isinstance(area, QtWidgets.QScrollArea) else area

    def indexOf(self, widget: QtWidgets.QWidget) -> int:  # noqa: N802 (Qt API)
        for index in range(self.count()):
            if widget is self.widget(index) or widget is self.page(index):
                return index
        return -1

    def setCurrentWidget(self, widget: QtWidgets.QWidget) -> None:  # noqa: N802 (Qt API)
        index = self.indexOf(widget)
        if index >= 0:
            self.setCurrentIndex(index)


