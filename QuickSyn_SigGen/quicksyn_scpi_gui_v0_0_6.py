class SerialTransport:
    """Thread-safe byte transport to the QuickSyn USB virtual COM port.

    Every public method takes a reentrant lock, so the GUI thread and the
    telemetry sampler thread can both talk to the instrument without
    interleaving bytes. The lock is deliberately the only serialisation
    mechanism: the device is half-duplex and cannot service concurrent
    requests, so there is nothing here to parallelise.

    Parameters
    ----------
    on_transaction:
        Optional callback invoked with a :class:`Transaction` after every
        exchange, successful or not. Used to drive the transaction log.
    """

    def __init__(
        self,
        on_transaction: Callable[[Transaction], None] | None = None,
    ) -> None:
        self._port: Any = None
        self._lock = threading.RLock()
        self._on_transaction = on_transaction
        self._last_tx_time: float = 0.0
        self.port_name: str = ""
        self.baudrate: int = DEFAULT_BAUD
        self.intercommand_gap_s: float = DEFAULT_INTERCOMMAND_GAP_S
        self.read_timeout_s: float = DEFAULT_READ_TIMEOUT_S

    # --- Lifecycle ----------------------------------------------------------
    @property
    def is_open(self) -> bool:
        """True when the underlying serial port is open."""
        return self._port is not None and getattr(self._port, "is_open", False)

    def open(
        self,
        port_name: str,
        baudrate: int = DEFAULT_BAUD,
        read_timeout_s: float = DEFAULT_READ_TIMEOUT_S,
    ) -> None:
        """Open the serial port using the vendor-mandated link parameters.

        Parameters
        ----------
        port_name:
            Platform port identifier, for example ``COM3`` or
            ``/dev/ttyUSB0``.
        baudrate:
            Line rate. The QuickSyn ships at 115200 and can be retargeted
            with ``DIAG:BAUD``; change this only after doing so.
        read_timeout_s:
            Per-read timeout.

        Raises
        ------
        TransportError
            If pyserial is unavailable or the port cannot be opened.
        """
        if not HAVE_PYSERIAL:
            raise TransportError(
                "pyserial is not installed; install it or use Simulator mode."
            )
        with self._lock:
            self.close()
            try:
                self._port = serial.Serial(
                    port=port_name,
                    baudrate=baudrate,
                    bytesize=SERIAL_BYTESIZE,
                    parity=SERIAL_PARITY,
                    stopbits=SERIAL_STOPBITS,
                    timeout=read_timeout_s,
                    write_timeout=DEFAULT_WRITE_TIMEOUT_S,
                    xonxoff=SERIAL_XONXOFF,
                    rtscts=SERIAL_RTSCTS,
                    dsrdtr=SERIAL_DSRDTR,
                )
            except Exception as exc:  # pyserial raises several types
                raise TransportError(
                    f"Could not open {port_name}: {exc}"
                ) from exc
            self.port_name = port_name
            self.baudrate = baudrate
            self.read_timeout_s = read_timeout_s
            self._port.reset_input_buffer()
            self._port.reset_output_buffer()

    def close(self) -> None:
        """Close the port if it is open. Safe to call repeatedly."""
        with self._lock:
            if self._port is not None:
                try:
                    self._port.close()
                except Exception:  # pragma: no cover - best effort
                    pass
            self._port = None

    # --- Low-level exchange -------------------------------------------------
    def _enforce_gap(self) -> None:
        """Sleep so that consecutive transactions are not back-to-back."""
        if self.intercommand_gap_s <= 0.0:
            return
        elapsed = time.monotonic() - self._last_tx_time
        if elapsed < self.intercommand_gap_s:
            time.sleep(self.intercommand_gap_s - elapsed)

    @staticmethod
    def encode(command: str) -> bytes:
        """Encode a command to bytes and enforce the 64-byte device buffer.

        Parameters
        ----------
        command:
            ASCII command text without a terminator.

        Returns
        -------
        bytes
            The command plus the CR terminator.

        Raises
        ------
        CommandTooLongError
            If the terminated command exceeds ``MAX_COMMAND_BYTES``.
        """
        payload = command.strip().encode("ascii", errors="strict") + TERMINATOR
        if len(payload) > MAX_COMMAND_BYTES:
            raise CommandTooLongError(
                f"{command!r} encodes to {len(payload)} bytes including the "
                f"terminator; the device buffer is {MAX_COMMAND_BYTES} bytes "
                f"[R1]."
            )
        return payload

    def _read_line(self, timeout_s: float) -> str:
        """Read until CR, LF or timeout and return the decoded text.

        [R1] does not state the terminator the instrument appends to its
        responses, so any of CR, LF or CRLF is accepted. See ambiguity
        note 3 in the module header.
        """
        deadline = time.monotonic() + timeout_s
        chunks = bytearray()
        while time.monotonic() < deadline:
            byte = self._port.read(1)
            if not byte:
                continue
            if byte in (b"\r", b"\n"):
                if chunks:
                    break
                continue  # tolerate a leading terminator from a prior reply
            chunks.extend(byte)
        return chunks.decode("ascii", errors="replace").strip()

    def _record(self, txn: Transaction) -> None:
        """Forward a completed transaction to the log callback, if any."""
        if self._on_transaction is not None:
            try:
                self._on_transaction(txn)
            except Exception:  # pragma: no cover - logging must never raise
                pass

    def write(self, command: str, settle_s: float = 0.0) -> None:
        """Send a command that produces no response.

        Parameters
        ----------
        command:
            SCPI command text without a terminator.
        settle_s:
            Mandatory post-command wait, from the delay table in [R1].

        Raises
        ------
        TransportError
            If the port is closed or the write fails.
        """
        payload = self.encode(command)
        with self._lock:
            if not self.is_open:
                raise TransportError("Serial port is not open.")
            self._enforce_gap()
            t0 = time.monotonic()
            t_unix = time.time()
            try:
                self._port.reset_input_buffer()
                self._port.write(payload)
                self._port.flush()
            except Exception as exc:
                self._record(
                    Transaction(
                        t_unix=t_unix,
                        command=command,
                        response=None,
                        latency_s=time.monotonic() - t0,
                        ok=False,
                        error=str(exc),
                        is_query=False,
                    )
                )
                raise TransportError(f"Write of {command!r} failed: {exc}") from exc
            if settle_s > 0.0:
                time.sleep(settle_s)
            self._last_tx_time = time.monotonic()
            self._record(
                Transaction(
                    t_unix=t_unix,
                    command=command,
                    response=None,
                    latency_s=self._last_tx_time - t0,
                    ok=True,
                    is_query=False,
                )
            )

    def query(
        self,
        command: str,
        repeat: int = 1,
        timeout_s: float | None = None,
    ) -> str:
        """Send a query and return the response text.

        Parameters
        ----------
        command:
            SCPI query text, normally ending in ``?``.
        repeat:
            Number of times the query is issued before the response is
            taken. [R1] requires two issues for the temperature query on
            the native interfaces; set ``repeat=2`` for that case.
        timeout_s:
            Override for the per-read timeout.

        Returns
        -------
        str
            The stripped response text, which may be empty on timeout.

        Raises
        ------
        TransportError
            If the port is closed or the exchange fails.
        """
        payload = self.encode(command)
        effective_timeout = timeout_s if timeout_s is not None else self.read_timeout_s
        with self._lock:
            if not self.is_open:
                raise TransportError("Serial port is not open.")
            self._enforce_gap()
            t0 = time.monotonic()
            t_unix = time.time()
            response = ""
            try:
                for issue in range(max(1, repeat)):
                    self._port.reset_input_buffer()
                    self._port.write(payload)
                    self._port.flush()
                    response = self._read_line(effective_timeout)
                    # Intermediate issues of a repeated query are discarded.
                    if issue < repeat - 1:
                        time.sleep(self.intercommand_gap_s)
            except Exception as exc:
                self._record(
                    Transaction(
                        t_unix=t_unix,
                        command=command,
                        response=None,
                        latency_s=time.monotonic() - t0,
                        ok=False,
                        error=str(exc),
                        is_query=True,
                    )
                )
                raise TransportError(f"Query {command!r} failed: {exc}") from exc
            self._last_tx_time = time.monotonic()
            self._record(
                Transaction(
                    t_unix=t_unix,
                    command=command,
                    response=response,
                    latency_s=self._last_tx_time - t0,
                    ok=bool(response),
                    error="" if response else "empty response (timeout)",
                    is_query=True,
                )
            )
            if not response:
                raise TransportError(
                    f"No response to {command!r} within {effective_timeout:.3f} s."
                )
            return response


