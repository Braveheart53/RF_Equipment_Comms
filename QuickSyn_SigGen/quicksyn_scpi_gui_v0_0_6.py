def main(argv: Sequence[str] | None = None) -> int:
    """Create the application, window and theme manager, then run the loop.

    Parameters
    ----------
    argv:
        Command-line arguments; ``sys.argv`` is used when omitted.
        ``--version`` (or ``-V``) prints the version banner and returns 0
        without creating a ``QApplication``.

    Returns
    -------
    int
        Qt exit code.
    """
    args = list(sys.argv if argv is None else argv)

    # --version needs no display and no QApplication.
    if any(arg in ("--version", "-V") for arg in args[1:]):
        print(version_banner())
        return 0

    if HAVE_PYQTGRAPH:
        pg.setConfigOptions(antialias=True, useOpenGL=False)

    app = QtWidgets.QApplication.instance() or QtWidgets.QApplication(args)
    app.setApplicationName(APP_NAME)
    app.setApplicationVersion(__version__)
    app.setOrganizationName(APP_ORG)

    theme = ThemeManager(app)
    theme.apply(ThemeManager.SYSTEM)

    window = MainWindow(theme)
    window.show()
    return app.exec()


if __name__ == "__main__":
    sys.exit(main())


