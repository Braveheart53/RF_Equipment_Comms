    def refresh_ports(self) -> None:
        """Repopulate the port list from pyserial's enumeration."""
        self.port_combo.clear()
        if not HAVE_PYSERIAL:
            self.port_combo.addItem("pyserial not installed", "")
            return
        found = list(list_ports.comports())
        if not found:
            self.port_combo.addItem("No serial ports found", "")
            return
        for info in found:
            # The QuickSyn enumerates through an FTDI-class bridge and
            # typically shows as "QuickSyn USB Interface" or FSW_USBSerial.
            label = f"{info.device} - {info.description}"
            self.port_combo.addItem(label, info.device)

    def selected_port(self) -> str:
        """Return the chosen device path, falling back to typed text."""
        data = self.port_combo.currentData()
        if data:
            return str(data)
        text = self.port_combo.currentText().strip()
        return text.split(" - ")[0] if text else ""

    def _emit_connect(self) -> None:
        """Validate the selection and emit :attr:`connectRequested`."""
        simulate = self.simulate_check.isChecked()
        port = self.selected_port()
        if not simulate and not port:
            QtWidgets.QMessageBox.warning(
                self, "No port", "Select a serial port or enable Simulator mode."
            )
            return
        self.connectRequested.emit(
            port or "SIM", int(self.baud_combo.currentData() or DEFAULT_BAUD), simulate
        )

    def set_connected(self, connected: bool) -> None:
        """Enable or disable the connection controls."""
        self.connect_button.setEnabled(not connected)
        self.disconnect_button.setEnabled(connected)
        self.port_combo.setEnabled(not connected)
        self.baud_combo.setEnabled(not connected)
        self.simulate_check.setEnabled(not connected)

