class SessionLogger:
    """Owns the on-disk artefacts for one acquisition session.

    Transaction and state-event rows are appended from whichever thread
    produced them, under a lock. Telemetry rows take a different path: they
    are queued and written by :class:`TelemetryWriter` so that disk latency
    never blocks the sampler.

    Parameters
    ----------
    root:
        Parent directory under which the session folder is created.
    tag:
        Short identifier appended to the folder name, normally the model
        and serial number.
    """

    def __init__(self, root: Path, tag: str = "quicksyn") -> None:
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_tag = re.sub(r"[^A-Za-z0-9_.-]+", "_", tag).strip("_") or "quicksyn"
        self.directory = Path(root).expanduser() / f"{stamp}_{safe_tag}"
        self.directory.mkdir(parents=True, exist_ok=True)

        self.path_metadata = self.directory / "session_metadata.json"
        self.path_session_log = self.directory / "session.log"
        self.path_transactions = self.directory / "transactions.csv"
        self.path_state_events = self.directory / "state_events.csv"
        self.path_telemetry = self.directory / "telemetry.csv"

        self._lock = threading.Lock()
        self._txn_count = 0
        self._state_count = 0
        self.t_start_unix = time.time()

        # --- Text log -------------------------------------------------------
        self.logger = logging.getLogger(f"quicksyn.{stamp}")
        self.logger.setLevel(logging.DEBUG)
        self.logger.propagate = False
        handler = logging.FileHandler(self.path_session_log, encoding="utf-8")
        handler.setFormatter(
            logging.Formatter(
                "%(asctime)s.%(msecs)03d  %(levelname)-8s  %(message)s",
                datefmt="%Y-%m-%d %H:%M:%S",
            )
        )
        self.logger.addHandler(handler)

        # --- CSV headers ----------------------------------------------------
        self._txn_file = open(
            self.path_transactions, "w", newline="", encoding="utf-8"
        )
        self._txn_writer = csv.writer(self._txn_file)
        self._txn_writer.writerow(
            [
                "seq",
                "iso_utc",
                "t_unix",
                "direction",
                "command",
                "response",
                "latency_ms",
                "ok",
                "error",
            ]
        )

        self._state_file = open(
            self.path_state_events, "w", newline="", encoding="utf-8"
        )
        self._state_writer = csv.writer(self._state_file)
        self._state_writer.writerow(
            ["seq", "iso_utc", "t_unix", "parameter", "value", "source"]
        )

        self.logger.info(
            "Session opened by %s v%s (%s, binding %s, Python %s)",
            APP_NAME,
            __version__,
            QT_ABSTRACTION,
            QT_BINDING,
            sys.version.split()[0],
        )

    # --- Writers ------------------------------------------------------------
    def log_transaction(self, txn: Transaction) -> None:
        """Append one SCPI exchange to transactions.csv and the text log."""
        with self._lock:
            self._txn_count += 1
            self._txn_writer.writerow(
                [
                    self._txn_count,
                    utc_iso(txn.t_unix),
                    f"{txn.t_unix:.6f}",
                    "QUERY" if txn.is_query else "WRITE",
                    txn.command,
                    "" if txn.response is None else txn.response,
                    f"{txn.latency_s * 1e3:.3f}",
                    int(txn.ok),
                    txn.error,
                ]
            )
            if self._txn_count % 50 == 0:
                self._txn_file.flush()
        if not txn.ok:
            self.logger.warning("TX FAILED %r: %s", txn.command, txn.error)

    def log_state_event(self, parameter: str, value: Any, source: str = "gui") -> None:
        """Append one generated-signal state change to state_events.csv."""
        t_unix = time.time()
        rendered = json.dumps(value) if isinstance(value, (dict, list)) else str(value)
        with self._lock:
            self._state_count += 1
            self._state_writer.writerow(
                [
                    self._state_count,
                    utc_iso(t_unix),
                    f"{t_unix:.6f}",
                    parameter,
                    rendered,
                    source,
                ]
            )
            self._state_file.flush()
        self.logger.info("STATE %s = %s (%s)", parameter, rendered, source)

    def write_metadata(self, payload: dict[str, Any]) -> None:
        """Write or rewrite session_metadata.json."""
        payload = dict(payload)
        payload.setdefault("app_name", APP_NAME)
        payload.setdefault("app_version", __version__)
        payload.setdefault("python_version", sys.version.split()[0])
        payload.setdefault("qt_abstraction", QT_ABSTRACTION)
        payload.setdefault("qt_binding", QT_BINDING)
        payload.setdefault("numpy_version", np.__version__)
        payload.setdefault("session_directory", str(self.directory))
        payload.setdefault("t_start_iso_utc", utc_iso(self.t_start_unix))
        with self._lock:
            self.path_metadata.write_text(
                json.dumps(payload, indent=2, default=str), encoding="utf-8"
            )

    def close(self) -> None:
        """Flush and close every open file handle."""
        with self._lock:
            for handle in (self._txn_file, self._state_file):
                try:
                    handle.flush()
                    handle.close()
                except Exception:  # pragma: no cover
                    pass
        self.logger.info("Session closed.")
        for handler in list(self.logger.handlers):
            handler.close()
            self.logger.removeHandler(handler)


