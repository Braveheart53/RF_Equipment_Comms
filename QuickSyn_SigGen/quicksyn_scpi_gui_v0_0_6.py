class AppController(QtCore.QObject):
    """Owns the transport, driver, session and sampler, and wires the tabs.

    The tabs hold no instrument state of their own; they call through to
    this object, which centralises error handling so that a failed
    transaction surfaces as a status-bar message and a log entry rather
    than an unhandled traceback.
    """

    #: Every SCPI exchange, with its source ("GUI" or "POLL"). Emitted from
    #: whichever thread made the exchange; Qt queues it to the GUI thread.
    transactionLogged = QtCore.Signal(object, str)

    def __init__(self, window: "MainWindow") -> None:
        super().__init__(window)
        self.window = window
        self.transport: SerialTransport | None = None
        self.driver: QuickSyn | None = None
        self.session: SessionLogger | None = None
        self.writer: TelemetryWriter | None = None
        self.ring: TelemetryRingBuffer | None = None
        self.sampler: TelemetrySampler | None = None
        self.sampler_errors = 0

        #: Buffers transactions produced before a session exists, so that
        #: the identity exchange at connect time still ends up in the log.
        self._pending_transactions: list[Transaction] = []

        self._ui_timer = QtCore.QTimer(self)
        self._ui_timer.setInterval(500)
        self._ui_timer.timeout.connect(self._refresh_statistics)

        #: Veusz document export state (see export_vszh5).
        self.last_session_dir: Path | None = None
        self._export_proc: QtCore.QProcess | None = None
        self._export_output: list[str] = []
        self._export_pending: tuple[Path, bool] | None = None
        self.last_export_ok: bool | None = None
        self._vszh5_timer = QtCore.QTimer(self)
        self._vszh5_timer.timeout.connect(
            lambda: self.export_vszh5(render=False, quiet=True)
        )

    # --- Error funnel -------------------------------------------------------
    def guard(self, action: Callable[[], Any]) -> Any:
        """Run an action, routing any failure to the status bar and log.

        Parameters
        ----------
        action:
            Zero-argument callable performing instrument work.

        Returns
        -------
        Any
            Whatever the action returned, or ``None`` on failure.
        """
        if self.driver is None:
            self.status_message("Not connected.")
            return None
        try:
            return action()
        except (QuickSynError, ValueError) as exc:
            self.status_message(f"Error: {exc}")
            if self.session is not None:
                self.session.logger.error("%s", exc)
            return None
        except Exception as exc:  # pragma: no cover - unexpected failure
            self.status_message(f"Unexpected error: {exc}")
            if self.session is not None:
                self.session.logger.exception("Unexpected error")
            return None

    def status_message(self, text: str) -> None:
        """Show a message on the main window status bar and in the log."""
        self.window.statusBar().showMessage(text, 10_000)
        if self.session is not None:
            self.session.logger.info("UI %s", text)

    # --- Transaction routing ------------------------------------------------
    def _on_transaction(self, txn: Transaction) -> None:
        """Route a transaction to the session log and the live console."""
        source = "GUI" if threading.current_thread() is threading.main_thread() else "POLL"
        self.transactionLogged.emit(txn, source)
        if self.session is not None:
            self.session.log_transaction(txn)
        else:
            self._pending_transactions.append(txn)
            # Keep the pre-session buffer bounded.
            if len(self._pending_transactions) > 5000:
                del self._pending_transactions[:1000]

    def _on_state_event(self, parameter: str, value: Any, source: str) -> None:
        """Route a commanded state change to the session log."""
        if self.session is not None:
            self.session.log_state_event(parameter, value, source)

    # --- Connection ---------------------------------------------------------
    def connect_instrument(self, port: str, baud: int, simulate: bool) -> None:
        """Open the transport, identify the unit and sync the UI."""
        try:
            tab = self.window.tab_connection
            factory = SimulatedTransport if simulate else SerialTransport
            transport = factory(on_transaction=self._on_transaction)
            transport.intercommand_gap_s = tab.gap_spin.value()
            transport.open(port, baud, tab.timeout_spin.value())
            self.transport = transport
            self.driver = QuickSyn(transport, on_state_event=self._on_state_event)

            ident = self.driver.identify()
            tab.show_identity(ident, self.driver.capability)
            tab.set_connected(True)
            self._apply_capability_limits()
            self.sync_from_instrument()

            if ident.scpi_supported is False:
                QtWidgets.QMessageBox.warning(
                    self.window,
                    "Firmware below the SCPI minimum",
                    f"This unit reports firmware {ident.firmware} "
                    f"({ident.firmware_value}), which is below the documented "
                    f"minimum of {MIN_SCPI_FIRMWARE} for SCPI support. "
                    f"Commands may be rejected. The native hexadecimal command "
                    f"set would be required instead; this application does not "
                    f"implement it.",
                )
            elif ident.scpi_supported is None:
                self.status_message(
                    f"Connected. Firmware field {ident.firmware!r} could not be "
                    f"parsed, so SCPI support was not confirmed."
                )
            else:
                self.status_message(
                    f"Connected to {ident.model} on {transport.port_name}"
                    + (" (simulated)." if simulate else ".")
                )
            self.window.set_connected(True)
        except QuickSynError as exc:
            QtWidgets.QMessageBox.critical(self.window, "Connection failed", str(exc))
            self.disconnect_instrument()

    def disconnect_instrument(self) -> None:
        """Stop acquisition if running and close the transport."""
        if self.sampler is not None:
            self.stop_logging()
        if self.transport is not None:
            self.transport.close()
        self.transport = None
        self.driver = None
        self.window.tab_connection.set_connected(False)
        self.window.set_connected(False)
        self.status_message("Disconnected.")

    def _apply_capability_limits(self) -> None:
        """Clamp the UI spin boxes to the detected model's documented limits."""
        if self.driver is None:
            return
        cap = self.driver.capability
        lower_ghz = (
            cap.f_min_opt1_hz if cap.f_min_opt1_hz is not None else cap.f_min_hz
        ) / 1e9
        upper_ghz = cap.f_max_hz / 1e9
        for spin in (
            self.window.tab_main.freq_spin,
            self.window.tab_sweep.start_freq,
            self.window.tab_sweep.stop_freq,
            self.window.tab_sweep.fixed_freq,
            self.window.tab_list.gen_start_f,
            self.window.tab_list.gen_stop_f,
            self.window.tab_memory.safe_freq,
        ):
            spin.setRange(lower_ghz, upper_ghz)
        # The FSL and mmW series expose no PULSE, AM or FM connectors
        # [R4], so offering those commands would be offering control over
        # hardware that is not fitted. Hide the tab instead.
        mod_index = self.window.tabs.indexOf(self.window.tab_modulation)
        if mod_index >= 0:
            self.window.tabs.setTabEnabled(mod_index, cap.has_modulation)
            self.window.tabs.setTabToolTip(
                mod_index,
                ""
                if cap.has_modulation
                else f"{cap.model} has no PULSE, AM or FM inputs [R4].",
            )
        for spin in (
            self.window.tab_main.power_spin,
            self.window.tab_sweep.start_power,
            self.window.tab_sweep.stop_power,
            self.window.tab_sweep.fixed_power,
            self.window.tab_list.gen_start_p,
            self.window.tab_list.gen_stop_p,
            self.window.tab_memory.safe_power,
        ):
            spin.setRange(cap.p_min_dbm, cap.p_max_dbm)

    def sync_from_instrument(self) -> None:
        """Read every settable parameter back and refresh the UI."""
        if self.driver is None:
            return
        d = self.driver
        main = self.window.tab_main
        main.freq_spin.setValue(d.get_frequency() / 1e9)
        main.power_spin.setValue(d.get_power())
        main.update_status(d.get_status())
        main.update_temperature(d.get_temperature())
        source = d.get_reference_source()
        index = main.refsrc_combo.findData(source)
        if index >= 0:
            main.refsrc_combo.blockSignals(True)
            main.refsrc_combo.setCurrentIndex(index)
            main.refsrc_combo.blockSignals(False)
        self.window.tab_modulation.update_modulation(d.get_modulation_status())

    # --- Acquisition --------------------------------------------------------
    def start_logging(self) -> None:
        """Open a session, start the writer thread and start sampling."""
        if self.driver is None:
            self.status_message("Connect to an instrument before logging.")
            return
        if self.sampler is not None:
            self.status_message("Logging is already running.")
            return

        monitor = self.window.tab_monitor
        config = monitor.config()
        root = Path(monitor.logdir_edit.text()).expanduser()
        try:
            root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            QtWidgets.QMessageBox.critical(
                self.window, "Log directory", f"Cannot create {root}: {exc}"
            )
            return

        ident = self.driver.identity
        tag = f"{ident.model or 'quicksyn'}_{ident.options or 'na'}"
        self.session = SessionLogger(root, tag=tag)

        # Drain anything captured before the session existed.
        for txn in self._pending_transactions:
            self.session.log_transaction(txn)
        self._pending_transactions.clear()

        self.writer = TelemetryWriter(self.session)
        self.writer.start()

        self.ring = TelemetryRingBuffer(
            capacity=monitor.ring_spin.value(),
            on_spill=self.writer.submit_spill,
        )

        self.session.write_metadata(
            {
                "identity": asdict(ident),
                "capability": asdict(self.driver.capability),
                "transport": {
                    "port": self.transport.port_name,
                    "baudrate": self.transport.baudrate,
                    "simulated": isinstance(self.transport, SimulatedTransport),
                    "intercommand_gap_s": self.transport.intercommand_gap_s,
                    "read_timeout_s": self.transport.read_timeout_s,
                    "terminator": "CR (0x0D)",
                    "max_command_bytes": MAX_COMMAND_BYTES,
                },
                "sampler": asdict(config),
                "temperature_double_query": TEMPERATURE_DOUBLE_QUERY,
                "ring_capacity": self.ring.capacity,
                "ring_bytes": self.ring.nbytes,
                "telemetry_dtype": TELEMETRY_DTYPE.descr,
            }
        )

        self.sampler_errors = 0
        self.sampler = TelemetrySampler(
            self.driver, config, self.ring, self.writer, parent=self
        )
        self.sampler.sampleReady.connect(self._on_sample)
        self.sampler.samplerError.connect(self._on_sampler_error)
        self.sampler.rateReport.connect(self._on_rate_report)
        self.sampler.start()

        monitor.set_running(True)
        self._ui_timer.start()
        minutes = monitor.vszh5_refresh.value()
        if minutes > 0:
            self._vszh5_timer.start(minutes * 60_000)
        self.status_message(
            f"Logging at {config.rate_hz:g} Hz into {self.session.directory}"
        )

    def stop_logging(self, detached_export: bool = False) -> None:
        """Stop sampling, flush the ring buffer and close the session.

        Parameters
        ----------
        detached_export:
            Start the end-of-session .vszh5 export as a detached process, so
            it completes even though the window is closing.
        """
        self._ui_timer.stop()
        self._vszh5_timer.stop()
        if self.sampler is not None:
            self.sampler.stop()
            self.sampler.wait(5000)
            self.sampler = None
        if self.ring is not None:
            remaining = self.ring.flush()
            if self.session is not None:
                self.session.logger.info(
                    "Flushed %d residual records at stop.", remaining.size
                )
        if self.writer is not None:
            self.writer.stop()
            if self.session is not None:
                self.session.logger.info(
                    "Writer committed %d rows and %d chunks (%d rows dropped).",
                    self.writer.rows_written,
                    self.writer.chunks_written,
                    self.writer.dropped_rows,
                )
            self.writer = None
        if self.session is not None:
            self.session.close()
            folder = self.session.directory
            self.session = None
            self.last_session_dir = folder
            self.status_message(f"Logging stopped. Session saved to {folder}")
            monitor = self.window.tab_monitor
            if monitor.chk_vszh5_stop.isChecked():
                self._launch_export(folder, monitor.chk_vszh5_render.isChecked(),
                                    detached=detached_export)
        self.ring = None
        self.window.tab_monitor.set_running(False)

    def flush_ram(self) -> None:
        """Spill the resident ring-buffer contents on demand."""
        if self.ring is None:
            self.status_message("No acquisition is running.")
            return
        block = self.ring.flush()
        self.status_message(f"Flushed {block.size} records from RAM to disk.")

    # --- Veusz document (.vszh5) --------------------------------------------
    def _session_folder(self) -> Path | None:
        """The running session's folder, else the last one, else None."""
        if self.session is not None:
            return self.session.directory
        return self.last_session_dir

    def export_vszh5(self, render: bool = False, quiet: bool = False) -> None:
        """Write (or rewrite) the session .vszh5 now.

        While logging, the RAM ring is first spilled to a chunk file and the
        writer thread is given time to commit it, so the document includes
        every sample up to this moment; acquisition continues meanwhile.
        """
        folder = self._session_folder()
        if folder is None:
            self.status_message("No session yet: start logging first.")
            return
        if self.ring is not None and self.writer is not None:
            self.ring.flush()
            self._wait_for_writer(folder, render, quiet, deadline=time.monotonic() + 15.0)
        else:
            self._launch_export(folder, render, quiet=quiet)

    def _wait_for_writer(self, folder: Path, render: bool, quiet: bool,
                         deadline: float) -> None:
        """Poll (without blocking the GUI) until the writer queue is empty."""
        writer = self.writer
        if writer is None or writer.queue.unfinished_tasks == 0 or time.monotonic() > deadline:
            self._launch_export(folder, render, quiet=quiet)
            return
        QtCore.QTimer.singleShot(
            100, lambda: self._wait_for_writer(folder, render, quiet, deadline)
        )

    def _export_command(self, folder: Path, render: bool) -> tuple[str, list[str]] | None:
        """Program and arguments that run the companion export script."""
        script = PROGRAM_DIR / COMPANION_EXPORT_SCRIPT
        if not script.is_file():
            self.status_message(f"{COMPANION_EXPORT_SCRIPT} not found beside the program; "
                                "cannot write the .vszh5.")
            return None
        axis = self.window.tab_monitor.vszh5_axis.currentData() or "local"
        args = [str(script), str(folder), "--time-axis", str(axis), "--workers", "2"]
        if not render:
            args.append("--no-render")
        return sys.executable, args

    def _launch_export(self, folder: Path, render: bool, detached: bool = False,
                       quiet: bool = False) -> None:
        """Run the export script for ``folder`` in a separate process."""
        command = self._export_command(folder, render)
        if command is None:
            return
        program, args = command
        if detached:
            QtCore.QProcess.startDetached(program, args)
            logging.getLogger(APP_NAME).info("Detached .vszh5 export: %s", folder)
            return
        if self._export_proc is not None:
            # One export at a time; the latest request runs when it finishes.
            self._export_pending = (folder, render)
            if not quiet:
                self.status_message("Veusz export already running; queued another.")
            return
        proc = QtCore.QProcess(self)
        proc.setProgram(program)
        proc.setArguments(args)
        proc.setWorkingDirectory(str(folder))
        proc.setProcessChannelMode(QtCore.QProcess.ProcessChannelMode.MergedChannels)
        self._export_output = []
        proc.readyReadStandardOutput.connect(
            lambda: self._export_output.append(
                bytes(proc.readAllStandardOutput()).decode("utf-8", "replace"))
        )
        proc.finished.connect(lambda *_: self._export_finished(folder))
        self._export_proc = proc
        self.last_export_ok = None
        proc.start()
        if not quiet:
            self.status_message(f"Writing Veusz document for {folder.name} ...")

    def _export_finished(self, folder: Path) -> None:
        """Report the export result and start any queued request."""
        proc = self._export_proc
        self._export_proc = None
        if proc is not None:
            self._export_output.append(
                bytes(proc.readAllStandardOutput()).decode("utf-8", "replace"))
        text = "".join(self._export_output).strip()
        code = proc.exitCode() if proc is not None else -1
        target = folder / SESSION_VSZH5_NAME
        self.last_export_ok = code == 0 and target.is_file()
        log = self.session.logger if self.session is not None else logging.getLogger(APP_NAME)
        log.info("Veusz export (exit %s):\n%s", code, text)
        if self.last_export_ok:
            extras = [ln.split(":", 1)[1].strip() for ln in text.splitlines()
                      if ln.startswith(("plots", "report")) and ":" in ln]
            self.status_message(f"Veusz document written: {target}"
                                + (f"  ({'; '.join(extras)})" if extras else ""))
        else:
            tail = text.splitlines()[-1] if text else "no output"
            self.status_message(f"Veusz export failed (exit {code}): {tail}")
        if proc is not None:
            proc.deleteLater()
        if self._export_pending is not None:
            pending, self._export_pending = self._export_pending, None
            self._launch_export(*pending)

    def open_in_veusz(self) -> None:
        """Open the session .vszh5 in the installed Veusz program."""
        folder = self._session_folder()
        target = folder / SESSION_VSZH5_NAME if folder is not None else None
        if target is None or not target.is_file():
            self.status_message("No .vszh5 yet: use 'Write .vszh5 now' first.")
            return
        exe = vszh5_writer.find_veusz_exe() if HAVE_VSZH5_WRITER else ""
        if exe:
            QtCore.QProcess.startDetached(exe, [str(target)])
            self.status_message(f"Opened {target.name} in Veusz.")
        else:
            QtGui.QDesktopServices.openUrl(QtCore.QUrl.fromLocalFile(str(target)))
            self.status_message("Veusz program not found; asked the desktop to open "
                                "the file. Set QUICKSYN_VEUSZ to veusz.exe.")

    # --- Sampler callbacks --------------------------------------------------
    def _on_sample(self, row: dict[str, Any]) -> None:
        """Update the headline readouts from the most recent sample."""
        monitor = self.window.tab_monitor
        monitor.set_stat("freq", row["freq_hz"] or "-")
        monitor.set_stat("power", row["power_dbm"] or "-")
        monitor.set_stat("temp", row["temp_c"] or "-")
        monitor.set_stat("latency", f"{float(row['latency_s']) * 1e3:.1f} ms")

    def _on_sampler_error(self, message: str) -> None:
        """Count and report a failed poll without stopping acquisition."""
        self.sampler_errors += 1
        self.window.tab_monitor.set_stat("errors", str(self.sampler_errors))
        if self.session is not None:
            self.session.logger.warning("Sampler: %s", message)

    def _on_rate_report(self, achieved_hz: float, duty: float) -> None:
        """Display the measured rate and the fraction of time spent in I/O."""
        monitor = self.window.tab_monitor
        monitor.set_stat("achieved", f"{achieved_hz:.2f} Hz")
        monitor.set_stat("duty", f"{duty * 100.0:.0f} %")
        if duty > 0.95:
            self.status_message(
                "Serial link is saturated; the requested sample rate is not "
                "being met. Reduce the rate or poll fewer fields."
            )

    def _refresh_statistics(self) -> None:
        """Periodic UI refresh for buffer, writer and plot state."""
        monitor = self.window.tab_monitor
        if self.ring is not None:
            monitor.set_stat("samples", f"{self.ring.total_written}")
            monitor.set_stat(
                "ring", f"{self.ring.fill} / {self.ring.capacity}"
            )
            monitor.set_stat("ram", f"{self.ring.nbytes / 1e6:.1f} MB")
            monitor.update_plot(self.ring.tail(DEFAULT_PLOT_WINDOW))
        if self.writer is not None:
            monitor.set_stat("chunks", str(self.writer.chunks_written))
            monitor.set_stat("rows", str(self.writer.rows_written))
            monitor.set_stat("queue", str(self.writer.queue.qsize()))
        if HAVE_PSUTIL:
            rss = psutil.Process(os.getpid()).memory_info().rss
            monitor.set_stat("rss", f"{rss / 1e6:.0f} MB")
        else:
            monitor.set_stat("rss", "psutil not installed")


