    def _panic_rf_off(self) -> None:
        """Mute the RF output immediately, whatever tab is in front."""
        self.controller.guard(
            lambda: self.controller.driver.set_rf_output(False)
        )
        self.tab_main.rf_check.setChecked(False)
        self.statusBar().showMessage("RF output muted.", 5000)

    def _build_about_box(self) -> QtWidgets.QMessageBox:
        """Construct the About dialog without showing it.

        The headline block carries version, author, company, a clickable
        email link, licence and copyright. The GPL notice is the informative
        text, and the interpreter and library versions sit behind "Show
        Details" so the dialog stays narrow.
        """
        content = build_about_content()
        box = QtWidgets.QMessageBox(self)
        box.setWindowTitle(f"About {APP_NAME}")
        box.setIcon(QtWidgets.QMessageBox.Icon.Information)
        box.setTextFormat(QtCore.Qt.TextFormat.RichText)
        box.setText(content["text"])
        box.setInformativeText(content["notice"])
        box.setDetailedText(content["runtime"])
        # Selectable text and clickable links (mailto: and the licence URL).
        box.setTextInteractionFlags(
            QtCore.Qt.TextInteractionFlag.TextBrowserInteraction
        )
        box.setStandardButtons(QtWidgets.QMessageBox.StandardButton.Ok)
        return box

