@dataclass(slots=True)
class SamplerConfig:
    """What the sampler polls and how often.

    Trimming the field set is the main lever on achievable rate: each
    enabled field costs one serial round trip, and the temperature query
    costs two when ``TEMPERATURE_DOUBLE_QUERY`` is set.
    """

    rate_hz: float = DEFAULT_SAMPLE_RATE_HZ
    poll_frequency: bool = True
    poll_power: bool = True
    poll_status: bool = True
    poll_modulation: bool = False
    poll_temperature: bool = True
    temperature_decimation: int = 5  # poll temperature every Nth sample

    @property
    def period_s(self) -> float:
        """Nominal sample period in seconds."""
        return 1.0 / max(self.rate_hz, MIN_SAMPLE_RATE_HZ)

    def queries_per_sample(self, include_temperature: bool = True) -> int:
        """Estimated serial round trips per sample, for rate budgeting."""
        count = 0
        count += int(self.poll_frequency)
        count += int(self.poll_power)
        count += int(self.poll_status)
        count += int(self.poll_modulation)
        if include_temperature and self.poll_temperature:
            count += 2 if TEMPERATURE_DOUBLE_QUERY else 1
        return count


class TelemetrySampler(QtCore.QThread):
    """Polls the instrument on a fixed schedule and emits telemetry records.

    Scheduling is absolute rather than incremental: the next deadline is
    computed from the acquisition start time and the sample index, so
    jitter in any one iteration does not accumulate into drift. If a sample
    overruns its slot, the overrun is reported rather than silently
    absorbed.

    Signals
    -------
    sampleReady(object)
        Emitted with the per-sample dictionary after each successful poll.
    samplerError(str)
        Emitted when a poll fails; acquisition continues.
    rateReport(float, float)
        Emitted with (achieved_rate_hz, duty_fraction) once per second.
    """

    sampleReady = QtCore.Signal(object)
    samplerError = QtCore.Signal(str)
    rateReport = QtCore.Signal(float, float)

    def __init__(
        self,
        driver: QuickSyn,
        config: SamplerConfig,
        ring: TelemetryRingBuffer,
        writer: TelemetryWriter,
        parent: QtCore.QObject | None = None,
    ) -> None:
        super().__init__(parent)
        self.driver = driver
        self.config = config
        self.ring = ring
        self.writer = writer
        self._running = False
        self._index = 0
        self._t0_mono = 0.0
        self._last_temp_c = float("nan")

    # --- Control ------------------------------------------------------------
    def stop(self) -> None:
        """Request an orderly stop; the run loop exits at the next check."""
        self._running = False

    # --- Thread body --------------------------------------------------------
    def run(self) -> None:
        """Acquire until stopped, honouring the configured sample period."""
        self._running = True
        self._index = 0
        self._t0_mono = time.monotonic()
        period = self.config.period_s
        last_report = self._t0_mono
        samples_in_window = 0
        busy_in_window = 0.0

        while self._running:
            deadline = self._t0_mono + (self._index + 1) * period
            t_poll_start = time.monotonic()
            try:
                record, row = self._poll_once(t_poll_start)
            except Exception as exc:
                self.samplerError.emit(str(exc))
                # Keep the cadence even when a poll fails, so the time base
                # of the log stays meaningful.
                self._index += 1
                self._sleep_until(deadline)
                continue

            busy = time.monotonic() - t_poll_start
            busy_in_window += busy
            samples_in_window += 1

            self.ring.append(record)
            self.writer.submit_row(row)
            self.sampleReady.emit(row)

            self._index += 1

            now = time.monotonic()
            if now - last_report >= 1.0:
                elapsed = now - last_report
                self.rateReport.emit(
                    samples_in_window / elapsed,
                    min(busy_in_window / elapsed, 1.0),
                )
                last_report = now
                samples_in_window = 0
                busy_in_window = 0.0

            self._sleep_until(deadline)

    def _sleep_until(self, deadline: float) -> None:
        """Sleep in short slices so a stop request is honoured promptly."""
        while self._running:
            remaining = deadline - time.monotonic()
            if remaining <= 0.0:
                return
            time.sleep(min(remaining, 0.05))

    def _poll_once(self, t_poll_start: float) -> tuple[tuple, dict[str, Any]]:
        """Execute one poll cycle and build both output representations.

        Returns
        -------
        tuple
            ``(numpy_record_tuple, csv_row_dict)``.
        """
        cfg = self.config
        t_unix = time.time()

        freq_hz = float("nan")
        power_dbm = float("nan")
        status = StatusWord()
        modword = ModulationWord()

        if cfg.poll_frequency:
            freq_hz = self.driver.get_frequency()
        if cfg.poll_power:
            power_dbm = self.driver.get_power()
        if cfg.poll_status:
            status = self.driver.get_status()
        if cfg.poll_modulation:
            modword = self.driver.get_modulation_status()

        # Temperature changes slowly, so it is decimated by default to buy
        # back serial bandwidth for the fast-moving fields.
        if cfg.poll_temperature and (
            cfg.temperature_decimation <= 1
            or self._index % cfg.temperature_decimation == 0
        ):
            self._last_temp_c = self.driver.get_temperature()
        temp_c = self._last_temp_c

        latency = time.monotonic() - t_poll_start
        t_mono = time.monotonic() - self._t0_mono
        rate_hz = 1.0 / latency if latency > 0 else 0.0

        record = (
            self._index,
            t_unix,
            t_mono,
            freq_hz,
            power_dbm,
            temp_c,
            status.raw,
            modword.raw,
            latency,
            rate_hz,
        )

        row = {
            "idx": self._index,
            "iso_utc": utc_iso(t_unix),
            "t_unix": f"{t_unix:.6f}",
            "t_mono_s": f"{t_mono:.6f}",
            "freq_hz": "" if math.isnan(freq_hz) else f"{freq_hz:.3f}",
            "power_dbm": "" if math.isnan(power_dbm) else f"{power_dbm:.2f}",
            "temp_c": "" if math.isnan(temp_c) else f"{temp_c:.2f}",
            "status_hex": f"{status.raw:02X}",
            "ext_ref_present": int(status.ext_ref_present),
            "rf_locked": int(status.rf_locked),
            "ref_locked": int(status.ref_locked),
            "rf_output_on": int(status.rf_output_on),
            "voltage_error": int(status.voltage_error),
            "ref_output_on": int(status.ref_output_on),
            "blanking_on": int(status.blanking_on),
            "lock_recovery_on": int(status.lock_recovery_on),
            "mod_hex": f"{modword.raw:02X}",
            "pulse_on": int(modword.pulse),
            "am_on": int(modword.am),
            "fm_nb1_on": int(modword.fm_nb1),
            "fm_nb2_on": int(modword.fm_nb2),
            "fm_wb_on": int(modword.fm_wide),
            "phase_on": int(modword.phase),
            "latency_s": f"{latency:.6f}",
            "rate_hz": f"{rate_hz:.3f}",
        }
        return record, row


