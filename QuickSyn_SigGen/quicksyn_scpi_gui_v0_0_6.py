# =============================================================================
class TelemetryRingBuffer:
    """Preallocated NumPy ring buffer with spill-to-disk on overflow.

    Memory is bounded by construction: ``capacity`` records of
    ``TELEMETRY_DTYPE`` (52 bytes each) are allocated once and reused. When
    the buffer fills, the whole block is handed to the spill callback and
    the write index resets, so steady-state RAM use is flat no matter how
    long the campaign runs.

    Parameters
    ----------
    capacity:
        Number of records held in RAM. Clamped up to ``MIN_RING_CAPACITY``
        so that a mistyped value cannot turn every sample into its own
        compressed chunk file; read :attr:`capacity` back for the value in
        force.
    on_spill:
        Callback receiving a copy of the filled block. Typically enqueues a
        gzip-pickle write on the writer thread.
    """

    def __init__(
        self,
        capacity: int = DEFAULT_RING_CAPACITY,
        on_spill: Callable[[np.ndarray], None] | None = None,
    ) -> None:
        self.capacity = int(max(capacity, MIN_RING_CAPACITY))
        self._data = np.zeros(self.capacity, dtype=TELEMETRY_DTYPE)
        self._write_index = 0
        self._total_written = 0
        self._lock = threading.Lock()
        self.on_spill = on_spill

    @property
    def nbytes(self) -> int:
        """Bytes of RAM held by the preallocated block."""
        return int(self._data.nbytes)

    @property
    def total_written(self) -> int:
        """Total records ever appended, including those already spilled."""
        return self._total_written

    @property
    def fill(self) -> int:
        """Records currently resident in RAM."""
        return self._write_index

    def append(self, record: tuple) -> None:
        """Append one record, spilling the block if it becomes full."""
        with self._lock:
            self._data[self._write_index] = record
            self._write_index += 1
            self._total_written += 1
            if self._write_index >= self.capacity:
                block = self._data.copy()
                self._write_index = 0
                if self.on_spill is not None:
                    self.on_spill(block)

    def tail(self, n: int) -> np.ndarray:
        """Return a copy of the most recent ``n`` resident records."""
        with self._lock:
            start = max(0, self._write_index - n)
            return self._data[start : self._write_index].copy()

    def flush(self) -> np.ndarray:
        """Spill and clear whatever is currently resident.

        Returns
        -------
        numpy.ndarray
            A copy of the records that were resident at the time of call.
        """
        with self._lock:
            block = self._data[: self._write_index].copy()
            self._write_index = 0
        if block.size and self.on_spill is not None:
            self.on_spill(block)
        return block


