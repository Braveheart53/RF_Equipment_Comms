class SimulatedTransport(SerialTransport):
    """Drop-in transport that emulates a QuickSyn FSW-0020.

    Useful for exercising the GUI, the logger and the sampler with no
    hardware attached. The state model covers every query this application
    issues; it is not a complete firmware model and makes no attempt to
    reproduce switching-time behaviour beyond a nominal delay.
    """

    def __init__(
        self,
        on_transaction: Callable[[Transaction], None] | None = None,
        model: str = "FSW-0020",
    ) -> None:
        super().__init__(on_transaction=on_transaction)
        self._open = False
        self._model = model
        self._state: dict[str, Any] = {
            "freq_mlhz": 10_000_000_000_000,   # 10 GHz default [R1/R2]
            "power_dbm": 13.0,
            "rf_out": False,
            "blanking": False,
            "ref_source": "INT",
            "ref_out": True,
            "pulse": False,
            "am": False,
            "am_dept": 0,
            "fm": False,
            "fm_mode": int(FMMode.FM_WIDE),
            "fm_sens": 0,
            "lock_recovery": True,
            "ref_dac": 30000,
        }
        self._t_start = time.monotonic()

    @property
    def is_open(self) -> bool:
        """True once :meth:`open` has been called."""
        return self._open

    def open(
        self,
        port_name: str = "SIM",
        baudrate: int = DEFAULT_BAUD,
        read_timeout_s: float = DEFAULT_READ_TIMEOUT_S,
    ) -> None:
        """Mark the simulated link as open."""
        with self._lock:
            self._open = True
            self.port_name = port_name
            self.baudrate = baudrate
            self.read_timeout_s = read_timeout_s

    def close(self) -> None:
        """Mark the simulated link as closed."""
        with self._lock:
            self._open = False

    # --- Command interpretation --------------------------------------------
    def _apply(self, command: str) -> str | None:
        """Update simulated state and return a response for queries."""
        cmd = command.strip()
        upper = cmd.upper()
        head, _, arg = cmd.partition(" ")
        head_u = head.upper()
        arg = arg.strip()

        match head_u:
            case "*IDN?":
                # Self-consistent under the inferred [R1] Table 4 field
                # order: manufacturer, model, option #, software version,
                # serial #. Firmware 0106 -> 106 decimal, which clears the
                # documented SCPI minimum of 100.
                return f"Phase Matrix,{self._model},00000007,0106,300A"
            case "*RST":
                # Factory defaults per [R1] Table 2a: RF output off, 10 GHz,
                # +15 dBm (FSW-0010) / +13 dBm (FSW-0020), internal
                # reference, reference output on, modulation off,
                # sensitivities 0. Blanking is left untouched because the
                # two manuals disagree (ambiguity note 1).
                self._state.update(
                    freq_mlhz=10_000_000_000_000,
                    power_dbm=13.0 if "0020" in self._model else 15.0,
                    rf_out=False,
                    pulse=False,
                    am=False,
                    fm=False,
                    am_dept=0,
                    fm_sens=0,
                )
                return None
            case "*SAV" | "*RCL":
                return None
            case "FREQ":
                self._state["freq_mlhz"] = self._parse_freq(arg)
                return None
            case "FREQ?":
                return str(int(self._state["freq_mlhz"]))
            case "POW":
                self._state["power_dbm"] = quantise_power_dbm(
                    parse_float_response(arg)
                )
                return None
            case "POW?":
                return f"{self._state['power_dbm']:.1f}"
            case "OUTP:STAT":
                self._state["rf_out"] = arg.upper() == "ON"
                return None
            case "OUTP:STAT?":
                return "1" if self._state["rf_out"] else "0"
            case "OUTP:BLAN":
                self._state["blanking"] = arg.upper() == "ON"
                return None
            case "OUTP:BLAN?":
                return "1" if self._state["blanking"] else "0"
            case "OUTP:ROSC:STAT":
                self._state["ref_out"] = arg.upper() == "ON"
                return None
            case "OUTP:ROSC:STAT?":
                return "1" if self._state["ref_out"] else "0"
            case "ROSC:SOUR":
                self._state["ref_source"] = arg.upper()
                return None
            case "ROSC:SOUR?":
                return str(self._state["ref_source"])
            case "PULM:STAT":
                self._state["pulse"] = arg.upper() == "ON"
                return None
            case "PULM:STAT?":
                return "1" if self._state["pulse"] else "0"
            case "AM:STAT":
                self._state["am"] = arg.upper() == "ON"
                return None
            case "AM:STAT?":
                return "1" if self._state["am"] else "0"
            case "AM:DEPT":
                self._state["am_dept"] = int(parse_float_response(arg))
                return None
            case "AM:DEPT?":
                return str(self._state["am_dept"])
            case "FM:STAT":
                self._state["fm"] = arg.upper() == "ON"
                return None
            case "FM:STAT?":
                return "1" if self._state["fm"] else "0"
            case "FM:MODE":
                self._state["fm_mode"] = int(parse_float_response(arg))
                return None
            case "FM:MODE?":
                return str(self._state["fm_mode"])
            case "FM:SENS":
                self._state["fm_sens"] = int(parse_float_response(arg))
                return None
            case "FM:SENS?":
                return str(self._state["fm_sens"])
            case "FREQ:LRSTAT":
                self._state["lock_recovery"] = arg.upper() == "ON"
                return None
            case "FREQ:LRSTAT?":
                return "1" if self._state["lock_recovery"] else "0"
            case "DIAG:CAL:REF:DAC":
                self._state["ref_dac"] = int(parse_float_response(arg))
                return None
            case "DIAG:CAL:REF:DAC?":
                return str(self._state["ref_dac"])
            case "STAT?":
                return f"{self._status_byte():04X}"
            case "DIAG:MOD?":
                return f"{self._mod_byte():02X}"
            case "DIAG:BAUD?":
                return str(self.baudrate)

        if upper.startswith("DIAG:MEAS?"):
            # Lazy thermal ramp towards 40 C plus a little noise.
            age = time.monotonic() - self._t_start
            temp = 29.0 + 11.0 * (1.0 - math.exp(-age / 900.0))
            temp += 0.05 * math.sin(age / 7.0)
            return f"{temp:.1f}"

        # Everything else (sweeps, lists, LIST:*, SWE:*) is accepted silently.
        return None

    @staticmethod
    def _parse_freq(arg: str) -> int:
        """Parse a ``FREQ`` argument into millihertz."""
        token = arg.strip().upper().replace(" ", "")
        multipliers = {"GHZ": 1e12, "MHZ": 1e9, "KHZ": 1e6, "MLHZ": 1.0,
                       "HZ": 1e3}
        for suffix, scale in multipliers.items():
            if token.endswith(suffix):
                return int(round(float(token[: -len(suffix)]) * scale))
        return int(round(float(token)))

    def _status_byte(self) -> int:
        """Assemble a plausible ``STAT?`` low byte from simulated state."""
        value = 0
        if self._state["ref_source"] == "EXT":
            value |= 1 << StatusBit.EXT_REF
        # Locked: leave RF_UNLOCKED and REF_UNLOCKED clear.
        if self._state["rf_out"]:
            value |= 1 << StatusBit.RF_OUTPUT_ON
        if self._state["ref_out"]:
            value |= 1 << StatusBit.REF_OUTPUT_ON
        if self._state["blanking"]:
            value |= 1 << StatusBit.BLANKING_ON
        if self._state["lock_recovery"]:
            value |= 1 << StatusBit.LOCK_RECOVERY
        return value

    def _mod_byte(self) -> int:
        """Assemble a plausible ``DIAG:MOD?`` low byte."""
        value = 0
        if self._state["pulse"]:
            value |= 1 << ModBit.PULSE
        if self._state["am"]:
            value |= 1 << ModBit.AM
        if self._state["fm"]:
            mode = FMMode(self._state["fm_mode"])
            bit = {
                FMMode.PHASE: ModBit.PHASE,
                FMMode.FM_WIDE: ModBit.FM_WIDE,
                FMMode.FM_NARROW1: ModBit.FM_NB1,
                FMMode.FM_NARROW2: ModBit.FM_NB2,
            }[mode]
            value |= 1 << bit
        return value

    # --- Transport interface ------------------------------------------------
    def write(self, command: str, settle_s: float = 0.0) -> None:
        """Apply a simulated command and record the transaction."""
        self.encode(command)  # still enforce the 64-byte limit
        with self._lock:
            if not self._open:
                raise TransportError("Simulated port is not open.")
            t0 = time.monotonic()
            t_unix = time.time()
            self._apply(command)
            time.sleep(max(settle_s, 0.0005))
            self._record(
                Transaction(
                    t_unix=t_unix,
                    command=command,
                    response=None,
                    latency_s=time.monotonic() - t0,
                    ok=True,
                    is_query=False,
                )
            )

    def query(
        self,
        command: str,
        repeat: int = 1,
        timeout_s: float | None = None,
    ) -> str:
        """Return a simulated response and record the transaction."""
        self.encode(command)
        with self._lock:
            if not self._open:
                raise TransportError("Simulated port is not open.")
            t0 = time.monotonic()
            t_unix = time.time()
            response = ""
            for _ in range(max(1, repeat)):
                response = self._apply(command) or ""
                time.sleep(0.0015)  # approximate a real round trip
            self._record(
                Transaction(
                    t_unix=t_unix,
                    command=command,
                    response=response,
                    latency_s=time.monotonic() - t0,
                    ok=bool(response),
                    error="" if response else "empty response (timeout)",
                    is_query=True,
                )
            )
            if not response:
                raise TransportError(f"No simulated response to {command!r}.")
            return response


