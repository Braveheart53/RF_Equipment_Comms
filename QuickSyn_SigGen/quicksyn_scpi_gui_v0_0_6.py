class TelemetryWriter(threading.Thread):
    """Daemon thread that owns all telemetry disk I/O.

    The sampler never touches the filesystem. It pushes work items onto a
    bounded queue and returns immediately; this thread drains the queue,
    appending CSV rows and writing gzip-pickle spill chunks. That keeps a
    stalled or slow disk from distorting the sample interval, which is the
    whole point of decoupling them.

    Work items are tuples ``("row", dict)`` or ``("spill", ndarray)``.
    """

    def __init__(self, session: SessionLogger, csv_flush_every: int = 25) -> None:
        super().__init__(name="telemetry-writer", daemon=True)
        self.session = session
        self.queue: queue.Queue = queue.Queue(maxsize=WRITER_QUEUE_MAXSIZE)
        self._stop_requested = threading.Event()
        self._csv_flush_every = max(1, csv_flush_every)
        self._rows_written = 0
        self._chunks_written = 0
        self.dropped_rows = 0

        self._csv_file = open(
            session.path_telemetry, "w", newline="", encoding="utf-8"
        )
        self._csv_writer = csv.DictWriter(
            self._csv_file, fieldnames=TELEMETRY_CSV_HEADER, extrasaction="ignore"
        )
        self._csv_writer.writeheader()

    # --- Producer-side API --------------------------------------------------
    def submit_row(self, row: dict[str, Any]) -> None:
        """Enqueue one telemetry CSV row; drop it rather than block."""
        try:
            self.queue.put_nowait(("row", row))
        except queue.Full:  # pragma: no cover - only under pathological load
            self.dropped_rows += 1

    def submit_spill(self, block: np.ndarray) -> None:
        """Enqueue a ring-buffer block for gzip-pickle serialisation."""
        try:
            self.queue.put(("spill", block), timeout=2.0)
        except queue.Full:  # pragma: no cover
            self.session.logger.error("Writer queue full; spill block dropped.")

    # --- Thread body --------------------------------------------------------
    def run(self) -> None:
        """Drain the queue until stopped and the queue is empty."""
        while not (self._stop_requested.is_set() and self.queue.empty()):
            try:
                kind, payload = self.queue.get(timeout=0.2)
            except queue.Empty:
                continue
            try:
                if kind == "row":
                    self._csv_writer.writerow(payload)
                    self._rows_written += 1
                    if self._rows_written % self._csv_flush_every == 0:
                        self._csv_file.flush()
                elif kind == "spill":
                    self._write_chunk(payload)
            except Exception as exc:  # pragma: no cover - keep the thread alive
                self.session.logger.exception("Writer error: %s", exc)
            finally:
                self.queue.task_done()
        self._close_csv()

    def _write_chunk(self, block: np.ndarray) -> None:
        """Serialise one ring-buffer block to a gzip-pickle chunk file."""
        path = (
            self.session.directory
            / f"telemetry_chunk_{self._chunks_written:04d}.pkl.gz"
        )
        # Written to .part and renamed, so the export script (which may run
        # while logging continues) never reads a half-written chunk.
        part = path.with_name(path.name + ".part")
        with gzip.open(part, "wb", compresslevel=5) as handle:
            pickle.dump(
                {
                    "dtype": TELEMETRY_DTYPE.descr,
                    "n_records": int(block.size),
                    "written_iso_utc": utc_iso(time.time()),
                    "records": block,
                },
                handle,
                protocol=pickle.HIGHEST_PROTOCOL,
            )
        os.replace(part, path)
        self._chunks_written += 1
        self.session.logger.info(
            "Spilled %d telemetry records to %s", block.size, path.name
        )

    def _close_csv(self) -> None:
        """Flush and close the telemetry CSV."""
        try:
            self._csv_file.flush()
            self._csv_file.close()
        except Exception:  # pragma: no cover
            pass

    def stop(self, timeout: float = 5.0) -> None:
        """Signal shutdown and wait for the queue to drain."""
        self._stop_requested.set()
        self.join(timeout=timeout)

    @property
    def rows_written(self) -> int:
        """Telemetry rows committed to CSV so far."""
        return self._rows_written

    @property
    def chunks_written(self) -> int:
        """Spill chunks written so far."""
        return self._chunks_written


