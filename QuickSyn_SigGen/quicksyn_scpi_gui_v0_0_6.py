def hz_to_mlhz(freq_hz: float) -> int:
    """Convert hertz to integer millihertz, the native command unit.

    [R1] gives millihertz (``mlHz``) as the default unit for ``FREQ`` and as
    the unit of the ``FREQ?`` response. Sending an integer avoids any
    dependence on the firmware's float parser and is exactly representable
    for the whole 0.1 GHz to 82 GHz span.

    Parameters
    ----------
    freq_hz:
        Frequency in hertz.

    Returns
    -------
    int
        Frequency in millihertz, rounded to the nearest integer.
    """
    return int(round(freq_hz * 1_000.0))


def mlhz_to_hz(freq_mlhz: float) -> float:
    """Convert the instrument's millihertz response back to hertz."""
    return float(freq_mlhz) / 1_000.0


def quantise_power_dbm(power_dbm: float) -> float:
    """Quantise a level to the 0.1 dB command granularity.

    Every documented QuickSyn power argument is expressed in tenth-dBm
    [R1, Tables 2a/5], so values finer than 0.1 dB cannot be commanded even
    though [R4] quotes 0.01 dB nominal resolution for the FSW-0010 with
    option 2. See ambiguity note 5 in the module header.
    """
    return round(power_dbm * 10.0) / 10.0


#: Accepted frequency units and their size in millihertz [R1, Table 5].
#: Bare "Hz" is deliberately absent: it is not in the documented list.
FREQ_UNIT_MLHZ: dict[str, int] = {
    "GHz": 1_000_000_000_000,
    "MHz": 1_000_000_000,
    "KHz": 1_000_000,
}


def format_frequency(freq_hz: float) -> str:
    """Encode a frequency in the shortest EXACT accepted representation.

    Compound commands such as ``LIST:PVEC`` and ``SWE:*:SETUP`` carry two or
    three frequencies plus every other parameter inside the 64-byte device
    buffer [R1, "USB Interface"]. A 20 GHz carrier in millihertz is 14
    characters, and three of those overflow the buffer on their own, which
    is why the [R1] examples all write frequencies with a GHz suffix. This
    function therefore evaluates every documented unit plus the millihertz
    default and returns whichever spelling is shortest.

    No candidate ever loses precision: millihertz is the instrument's
    resolution, so dividing by a power of ten and trimming trailing zeros
    is exact by construction.

    Parameters
    ----------
    freq_hz:
        Frequency in hertz.

    Returns
    -------
    str
        For example ``"2GHz"``, ``"9.111222333GHz"`` or ``"9876543210000"``
        (millihertz, the documented default unit). Ties resolve in favour
        of the millihertz form because it is the documented default.

    Examples
    --------
    >>> format_frequency(2.0e9)
    '2GHz'
    >>> format_frequency(10.0e9)
    '10GHz'
    """
    mlhz = hz_to_mlhz(freq_hz)
    best = str(mlhz)                      # documented default unit
    for suffix, scale in FREQ_UNIT_MLHZ.items():
        whole, remainder = divmod(abs(mlhz), scale)
        digits = len(str(scale)) - 1      # fractional digits needed at most
        body = f"{'-' if mlhz < 0 else ''}{whole}"
        if remainder:
            body += f".{remainder:0{digits}d}".rstrip("0")
        candidate = f"{body}{suffix}"
        if len(candidate) < len(best):
            best = candidate
    return best


def quantise_dwell_us(dwell_us: int) -> int:
    """Quantise a dwell time to the instrument's 5 us granularity.

    [R1] Tables 2b and 2c specify the dwell field as "Dwell time in usec
    (5 to 4,294,967,295 (~1hr)) in 5us increments", so a value that is not
    a multiple of 5 us cannot be represented. Rounding here, rather than
    letting the firmware truncate silently, means the logged command is the
    command the instrument actually executes.

    Parameters
    ----------
    dwell_us:
        Requested dwell time in microseconds.

    Returns
    -------
    int
        The nearest multiple of 5 us, clamped to the documented range. Zero
        is passed through unchanged because ``LIST:SETUP`` treats a zero
        global dwell as "use each point's own dwell" [R1, Table 2b].
    """
    if dwell_us <= 0:
        return 0
    quantised = int(round(dwell_us / DWELL_INCREMENT_US)) * DWELL_INCREMENT_US
    return max(DWELL_MIN_US, min(quantised, DWELL_MAX_US))


def format_dwell(dwell_us: int) -> str:
    """Render a dwell time in the most compact accepted unit.

    ``LIST:PVEC`` and the sweep setup commands accept ``us``, ``ms`` or
    ``s``, defaulting to microseconds [R1, Table 5]. Choosing the compact
    form matters because the whole command must fit in 64 bytes. The value
    is quantised to 5 us first.

    Parameters
    ----------
    dwell_us:
        Dwell time in microseconds, 5 to 4 294 967 295.

    Returns
    -------
    str
        For example ``"2500us"``, ``"50ms"`` or ``"3s"``.
    """
    dwell_us = quantise_dwell_us(dwell_us)
    if dwell_us % 1_000_000 == 0 and dwell_us >= 1_000_000:
        return f"{dwell_us // 1_000_000}s"
    if dwell_us % 1_000 == 0 and dwell_us >= 1_000:
        return f"{dwell_us // 1_000}ms"
    return f"{dwell_us}us"


def utc_iso(t_unix: float) -> str:
    """Format an epoch time as an ISO-8601 UTC string with milliseconds."""
    return (
        datetime.fromtimestamp(t_unix, tz=timezone.utc)
        .isoformat(timespec="milliseconds")
        .replace("+00:00", "Z")
    )


def parse_int_response(text: str) -> int:
    """Parse a response that may be decimal or hexadecimal.

    ``STAT?`` and ``DIAG:MOD?`` return values such as ``00A8`` and ``10``
    [R1, Table 5]. ``00A8`` is unambiguously hexadecimal; ``10`` is not.
    Because every documented example of these two queries is a hex string,
    hexadecimal is tried first and decimal is used only as a fallback.

    Parameters
    ----------
    text:
        Raw response text.

    Returns
    -------
    int
        Decoded integer value.

    Raises
    ------
    ValueError
        If the text parses as neither hexadecimal nor decimal.
    """
    cleaned = text.strip().removeprefix("0x").removeprefix("0X")
    if not cleaned:
        raise ValueError("empty integer response")
    try:
        return int(cleaned, 16)
    except ValueError:
        return int(cleaned, 10)


def parse_float_response(text: str) -> float:
    """Extract the first signed decimal number from a response string."""
    match = re.search(r"[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", text)
    if match is None:
        raise ValueError(f"no numeric field in response {text!r}")
    return float(match.group(0))


def parse_bool_response(text: str) -> bool:
    """Interpret a 1/0 or ON/OFF response as a boolean."""
    token = text.strip().upper()
    if token in {"1", "ON", "TRUE"}:
        return True
    if token in {"0", "OFF", "FALSE"}:
        return False
    # Some firmware revisions echo the numeric form with padding.
    try:
        return bool(int(token))
    except ValueError as exc:
        raise ValueError(f"cannot interpret {text!r} as boolean") from exc


