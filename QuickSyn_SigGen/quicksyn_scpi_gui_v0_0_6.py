    # --- Table helpers ------------------------------------------------------
    def _append_row(
        self,
        index: int,
        freq_ghz: float,
        power_dbm: float,
        dwell_us: int,
        pulse: bool,
        rf_on: bool,
    ) -> None:
        """Append one editable row to the point table."""
        row = self.table.rowCount()
        self.table.insertRow(row)
        values = [
            str(index),
            f"{freq_ghz:.6f}",
            f"{power_dbm:.1f}",
            str(dwell_us),
        ]
        for column, text in enumerate(values):
            self.table.setItem(row, column, QtWidgets.QTableWidgetItem(text))
        for column, state in ((4, pulse), (5, rf_on)):
            item = QtWidgets.QTableWidgetItem()
            item.setFlags(
                QtCore.Qt.ItemFlag.ItemIsUserCheckable
                | QtCore.Qt.ItemFlag.ItemIsEnabled
            )
            item.setCheckState(
                QtCore.Qt.CheckState.Checked if state
                else QtCore.Qt.CheckState.Unchecked
            )
            self.table.setItem(row, column, item)

    def _generate(self) -> None:
        """Fill the table with a linear frequency and power ramp."""
        self.table.setRowCount(0)
        n = self.gen_points.value()
        f0, f1 = self.gen_start_f.value(), self.gen_stop_f.value()
        p0, p1 = self.gen_start_p.value(), self.gen_stop_p.value()
        dwell = self.gen_dwell.value()
        freqs = np.linspace(f0, f1, n) if n > 1 else np.array([f0])
        powers = np.linspace(p0, p1, n) if n > 1 else np.array([p0])
        for i in range(n):
            self._append_row(i + 1, float(freqs[i]), float(powers[i]), dwell,
                             False, True)

    def _delete_selected(self) -> None:
        """Remove the selected rows and renumber the remainder."""
        rows = sorted({idx.row() for idx in self.table.selectedIndexes()},
                      reverse=True)
        for row in rows:
            self.table.removeRow(row)
        for row in range(self.table.rowCount()):
            self.table.item(row, 0).setText(str(row + 1))

    def collect_points(self) -> list[ListPoint]:
        """Read the table into a list of :class:`ListPoint` records."""
        points: list[ListPoint] = []
        flash = self.flash_check.isChecked()
        for row in range(self.table.rowCount()):
            try:
                index = int(self.table.item(row, 0).text())
                freq_ghz = float(self.table.item(row, 1).text())
                power = float(self.table.item(row, 2).text())
                dwell = int(float(self.table.item(row, 3).text()))
            except (AttributeError, ValueError) as exc:
                raise ParameterError(f"Row {row + 1} is not valid: {exc}") from exc
            pulse = (
                self.table.item(row, 4).checkState()
                == QtCore.Qt.CheckState.Checked
            )
            rf_on = (
                self.table.item(row, 5).checkState()
                == QtCore.Qt.CheckState.Checked
            )
            points.append(
                ListPoint(
                    index=index,
                    freq_hz=freq_ghz * 1e9,
                    power_dbm=power,
                    dwell_us=dwell,
                    pulse_mod=pulse,
                    rf_output=rf_on,
                    save_to_flash=flash,
                )
            )
        return points

    def _import_csv(self) -> None:
        """Load a point table from CSV."""
        path, _ = QtWidgets.QFileDialog.getOpenFileName(
            self, "Import list points", "", "CSV files (*.csv);;All files (*)"
        )
        if not path:
            return
        self.table.setRowCount(0)
        with open(path, newline="", encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                self._append_row(
                    int(row.get("point", self.table.rowCount() + 1)),
                    float(row.get("freq_ghz", 0.0)),
                    float(row.get("power_dbm", 0.0)),
                    int(float(row.get("dwell_us", 50_000))),
                    str(row.get("pulse_mod", "0")).strip() in {"1", "True", "true"},
                    str(row.get("rf_output", "1")).strip() in {"1", "True", "true"},
                )

    def _export_csv(self) -> None:
        """Save the point table to CSV."""
        path, _ = QtWidgets.QFileDialog.getSaveFileName(
            self, "Export list points", "list_points.csv",
            "CSV files (*.csv);;All files (*)"
        )
        if not path:
            return
        with open(path, "w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(
                ["point", "freq_ghz", "power_dbm", "dwell_us",
                 "pulse_mod", "rf_output"]
            )
            for point in self.collect_points():
                writer.writerow(
                    [
                        point.index,
                        f"{point.freq_hz / 1e9:.9f}",
                        f"{point.power_dbm:.1f}",
                        point.dwell_us,
                        int(point.pulse_mod),
                        int(point.rf_output),
                    ]
                )

    # --- Device operations --------------------------------------------------
    def _download(self) -> None:
        """Erase the list and download every point in the table."""
        points = self.collect_points()
        if not points:
            raise ParameterError("The point table is empty.")
        flash = self.flash_check.isChecked()
        if flash:
            answer = QtWidgets.QMessageBox.question(
                self,
                "Write to flash?",
                f"Writing {len(points)} points to flash takes about "
                f"{len(points) * WAIT_LIST_POINT_FLASH_S:.0f} s and consumes "
                f"non-volatile user memory. RAM-only download is the "
                f"recommended default. Continue?",
            )
            if answer != QtWidgets.QMessageBox.StandardButton.Yes:
                return

        self.progress.setVisible(True)
        self.progress.setRange(0, len(points))
        self.ctl.driver.erase_list()
        for n, point in enumerate(points, start=1):
            self.ctl.driver.write_list_point(point)
            self.progress.setValue(n)
            QtWidgets.QApplication.processEvents()
        if flash:
            self.ctl.driver.save_list(len(points))
        self.progress.setVisible(False)
        self.ctl.status_message(
            f"Downloaded {len(points)} list points "
            f"({'flash' if flash else 'RAM only'})."
        )

    def _setup_and_run(self) -> None:
        """Configure traversal and start it."""
        self.ctl.driver.setup_list(
            dwell_us=self.global_dwell.value(),
            run_count=self.run_count.value(),
            trigger=self.list_trigger.currentData(),
            direction=self.list_direction.currentData(),
            run_now=True,
        )
        self.ctl.status_message("List running.")


