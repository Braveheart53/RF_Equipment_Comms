def _check_compound_length(command: str, hint: str) -> None:
    """Pre-flight a compound command against the 64-byte device buffer.

    The transport enforces the limit anyway, but a bare byte count is not
    actionable to an operator staring at a sweep dialog. This raises the
    same condition with advice on which parameter to shorten.

    Parameters
    ----------
    command:
        The fully formatted command, without its terminator.
    hint:
        What the operator can change to make it fit.

    Raises
    ------
    CommandTooLongError
        If the terminated command would exceed ``MAX_COMMAND_BYTES``.
    """
    encoded = len(command.encode("ascii", errors="replace")) + len(TERMINATOR)
    if encoded > MAX_COMMAND_BYTES:
        raise CommandTooLongError(
            f"This command needs {encoded} bytes but the QuickSyn serial "
            f"buffer holds only {MAX_COMMAND_BYTES} including the terminator "
            f"[R1]. {hint}\n\n{command}"
        )


